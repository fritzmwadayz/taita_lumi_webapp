"""SQLAlchemy models — all 10 tables.

Schema notes:
  - No 'senses' table: translations attach directly to words.
    Voting targets words, keeping the model simple for v1.
  - UUIDs generated by Postgres (gen_random_uuid()).
  - All timestamps are timezone-aware.
  - votes CHECK constraint ensures exactly one of user_id/session_id is set.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship
from sqlalchemy.sql import func


class Base(DeclarativeBase):
    """Base class for all models."""

    pass



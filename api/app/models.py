class WordVariation(Base):
    """A bidirectional link between two forms of the SAME lemma.

    Examples: mlima ↔ milima (singular ↔ plural), kuja ↔ anakuja (lemma ↔ conjugation).
    Always symmetric — the row (A, B, type) means "A and B are variations of each other".

    variation_type ∈ {'variant', 'plural', 'singular', 'conjugation',
                       'diminutive', 'augmentative'}

    The unique index uses LEAST/GREATEST on (word_id, other_word_id) so that
    (A, B, 'plural') and (B, A, 'plural') can't both exist — they're the same link.
    """

    __tablename__ = "word_variations"
    __table_args__ = (
        CheckConstraint("word_id <> other_word_id", name="ck_word_variations_no_self"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    other_word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    variation_type: Mapped[str] = mapped_column(
        Text, nullable=False, index=True
    )  # 'variant' | 'plural' | 'singular' | 'conjugation' | 'diminutive' | 'augmentative'
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


class WordRelationship(Base):
    """A typed link between two DIFFERENT lemmas.

    Examples: kuja ↔ enda (antonyms), run → runner (derived).

    direction ∈ {'bidirectional', 'forward', 'reverse'}:
      - 'bidirectional' (default for antonym, synonym, see_also):
        the relationship is symmetric — (A, B, 'antonym') means A and B are
        antonyms of each other.
      - 'forward' (default for derived, etymological):
        the relationship is directional — (A, B, 'derived', 'forward') means
        A is derived FROM B. The reverse (B → A) is not implied.
      - 'reverse': stored for completeness; the word detail endpoint surfaces
        forward relationships as 'outgoing' and reverse ones as 'incoming'
        (only relevant if you want to flip a previously-created link).

    relationship_type ∈ {'antonym', 'synonym', 'see_also', 'derived', 'etymological'}
    """

    __tablename__ = "word_relationships"
    __table_args__ = (
        CheckConstraint("word_id <> other_word_id", name="ck_word_relationships_no_self"),
        CheckConstraint(
            "direction IN ('bidirectional', 'forward', 'reverse')",
            name="ck_word_relationships_direction",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    other_word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    relationship_type: Mapped[str] = mapped_column(
        Text, nullable=False, index=True
    )  # 'antonym' | 'synonym' | 'see_also' | 'derived' | 'etymological'
    direction: Mapped[str] = mapped_column(
        Text, nullable=False, server_default="bidirectional"
    )  # 'bidirectional' | 'forward' | 'reverse'
    note: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )



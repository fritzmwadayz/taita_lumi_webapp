class Word(Base):
    """The primary unit — a Taita headword.

    Variations and plurals are separate Word rows, linked via WordRelation.
    status: 'live' (visible), 'hidden' (soft-deleted), 'merged' (redirected).
    source: 'import' (from lexicon.db), 'user' (contributor), 'anon' (suggestion accepted).
    """

    __tablename__ = "words"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    headword: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    normalized_form: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    slug: Mapped[str] = mapped_column(Text, nullable=False, unique=True, index=True)
    part_of_speech: Mapped[str | None] = mapped_column(Text, nullable=True)
    noun_class: Mapped[str | None] = mapped_column(Text, nullable=True)
    dialect: Mapped[str | None] = mapped_column(Text, nullable=True)
    literal_translation: Mapped[str | None] = mapped_column(Text, nullable=True)
    morphology_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    status: Mapped[str] = mapped_column(
        Text, nullable=False, server_default="live", index=True
    )
    source: Mapped[str] = mapped_column(Text, nullable=False)
    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id"), nullable=True
    )
    created_by_session_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("anonymous_sessions.id"), nullable=True
    )
    import_batch_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("import_batches.id"), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    reviewed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    reviewed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id"), nullable=True
    )

    # Relationships
    translations: Mapped[list["Translation"]] = relationship(
        back_populates="word", cascade="all, delete-orphan"
    )
    examples: Mapped[list["Example"]] = relationship(
        back_populates="word", cascade="all, delete-orphan"
    )
    senses: Mapped[list["Sense"]] = relationship(
        primaryjoin="Word.id == Sense.word_id",
        order_by="Sense.order_index",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )


class Translation(Base):
    """A translation of a word in a specific language ('en' or 'sw').

    Strictly scoped to a single Sense (sense_id). For backward compat,
    sense_id is nullable in the DB but the API populates it on every
    new translation. Pre-senses translations were backfilled to a default
    sense per word during migration 0005.

    (Renamed from Gloss in v1.3 — "translation" is more intuitive than
    "gloss" for non-lexicographers. The DB table was renamed from
    `glosses` to `translations` in migration 0006.)
    """

    __tablename__ = "translations"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    sense_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("senses.id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )
    language: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    word: Mapped["Word"] = relationship(back_populates="translations")



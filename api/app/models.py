"""SQLAlchemy models — all 10 tables.

Schema notes:
  - No 'senses' table: glosses attach directly to words.
    Voting targets words, keeping the model simple for v1.
  - UUIDs generated by Postgres (gen_random_uuid()).
  - All timestamps are timezone-aware.
  - votes CHECK constraint ensures exactly one of user_id/session_id is set.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship
from sqlalchemy.sql import func


class Base(DeclarativeBase):
    """Base class for all models."""

    pass


# ═══════════════════════════════════════════════════════════════
# Users & Sessions
# ═══════════════════════════════════════════════════════════════


class User(Base):
    """Account holder — contributor or admin. Anon visitors use AnonymousSession."""

    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    email: Mapped[str] = mapped_column(Text, unique=True, nullable=False, index=True)
    password_hash: Mapped[str | None] = mapped_column(Text, nullable=True)
    oauth_provider: Mapped[str | None] = mapped_column(Text, nullable=True)
    oauth_subject: Mapped[str | None] = mapped_column(Text, nullable=True)
    display_name: Mapped[str | None] = mapped_column(Text, nullable=True)
    role: Mapped[str] = mapped_column(
        Text, nullable=False, server_default="contributor"
    )
    is_blocked: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default="false"
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    last_seen_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )


class AnonymousSession(Base):
    """Tracks anon visitors for rate-limiting and spam control."""

    __tablename__ = "anonymous_sessions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    cookie_hash: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    ip_hash: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    is_blocked: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default="false"
    )


# ═══════════════════════════════════════════════════════════════
# Words, Glosses, Examples, Relations
# ═══════════════════════════════════════════════════════════════


class Word(Base):
    """The primary unit — a Taita headword.

    Variations and plurals are separate Word rows, linked via WordRelation.
    status: 'live' (visible), 'hidden' (soft-deleted), 'merged' (redirected).
    source: 'import' (from lexicon.db), 'user' (contributor), 'anon' (suggestion accepted).
    """

    __tablename__ = "words"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    headword: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    normalized_form: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    part_of_speech: Mapped[str | None] = mapped_column(Text, nullable=True)
    noun_class: Mapped[str | None] = mapped_column(Text, nullable=True)
    dialect: Mapped[str | None] = mapped_column(Text, nullable=True)
    literal_translation: Mapped[str | None] = mapped_column(Text, nullable=True)
    morphology_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    status: Mapped[str] = mapped_column(
        Text, nullable=False, server_default="live", index=True
    )
    source: Mapped[str] = mapped_column(Text, nullable=False)
    created_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id"), nullable=True
    )
    created_by_session_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("anonymous_sessions.id"), nullable=True
    )
    import_batch_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("import_batches.id"), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    reviewed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    reviewed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id"), nullable=True
    )

    # Relationships
    glosses: Mapped[list["Gloss"]] = relationship(
        back_populates="word", cascade="all, delete-orphan"
    )
    examples: Mapped[list["Example"]] = relationship(
        back_populates="word", cascade="all, delete-orphan"
    )


class Gloss(Base):
    """A translation of a word in a specific language ('en' or 'sw')."""

    __tablename__ = "glosses"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    language: Mapped[str] = mapped_column(Text, nullable=False, index=True)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    word: Mapped["Word"] = relationship(back_populates="glosses")


class Example(Base):
    """A usage example with parallel text in Taita / Swahili / English."""

    __tablename__ = "examples"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    taita_text: Mapped[str] = mapped_column(Text, nullable=False)
    swahili_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    english_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    source_ref: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    word: Mapped["Word"] = relationship(back_populates="examples")


class WordRelation(Base):
    """An edge between two words (plural, singular, variant, etc.).

    Convention: store both directions for symmetric pairs (plural/singular = 2 rows).
    For asymmetric (derived), one row suffices.
    """

    __tablename__ = "word_relations"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid()
    )
    from_word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    to_word_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("words.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    relation_type: Mapped[str] = mapped_column(
        Text, nullable=False, index=True
    )  # 'plural' | 'singular' | 'variant' | 'diminutive' | 'augmentative' | 'derived' | 'see_also'
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )



// https://nuxt.com/docs/api/configuration/nuxt-config
// Lumi — Nuxt 4 port of the Vue 3 SPA. SSR for public pages, SPA-mode for authed routes.
// Deploy target: Netlify (free tier). Backend on Render, DB on Neon.

export default defineNuxtConfig({
  compatibilityDate: '2025-07-15',
  devtools: { enabled: true },

  // ── Modules ────────────────────────────────────────────────────────────
  modules: [
    '@nuxtjs/tailwindcss', // Tailwind v3 (stays on v3 — deferred migration to v4)
    '@nuxt/fonts',         // Self-host Inter + Source Serif 4
    'nuxt-auth-utils',     // Server-side session, OAuth helpers
  ],

  // ── SSR ────────────────────────────────────────────────────────────────
  // Global SSR on. Authed pages (/login, /me, /admin, /review) opt out via
  // definePageMeta({ ssr: false }) in their page components (Phase 4+).
  ssr: true,

  // ── CSS ────────────────────────────────────────────────────────────────
  // main.css = design tokens + primitives; motion.css = transitions,
  // skeletons, toasts, success overlay (plain CSS, no Tailwind directives).
  css: ['~/assets/css/main.css'],

  // ── Tailwind ───────────────────────────────────────────────────────────
  tailwindcss: {
    configPath: '~/tailwind.config.js',
    cssPath: '~/assets/css/main.css',
    viewer: false, // disable tailwind viewer in dev (not needed)
  },

  // ── Fonts (self-hosted via @nuxt/fonts) ────────────────────────────────
  // Auto-detects font families from CSS/HTML and downloads them locally.
  // Inter + Source Serif 4 are declared in tailwind.config.js → picked up here.
  fonts: {
    families: [
      { name: 'Inter', provider: 'google' },
      { name: 'Source Serif 4', provider: 'google' },
    ],
  },

  // ── Runtime config ─────────────────────────────────────────────────────
  // IMPORTANT: do NOT read process.env.* for secrets here. Values assigned in
  // nuxt.config are BAKED into the Nitro server bundle at build time — so any
  // env var read here ends up in .netlify/functions-internal/.../nitro.mjs,
  // and Netlify's secrets scanner will block the deploy.
  //
  // Instead, leave the defaults empty (or a dev-only localhost fallback) and
  // let Nuxt's runtime override inject the real values at request time:
  //   runtimeConfig.apiBase             ← NUXT_API_BASE
  //   runtimeConfig.oauth.google.clientId     ← NUXT_OAUTH_GOOGLE_CLIENT_ID
  //   runtimeConfig.oauth.google.clientSecret ← NUXT_OAUTH_GOOGLE_CLIENT_SECRET
  //   runtimeConfig.session.password          ← NUXT_SESSION_PASSWORD (nuxt-auth-utils)
  // The bundle ships with empty strings → scanner sees nothing → deploy passes.
  runtimeConfig: {
    // Server-only (never exposed to client). localhost fallback is dev-only;
    // in production NUXT_API_BASE overrides it at runtime.
    apiBase: 'http://localhost:8000',
    // OAuth: nuxt-auth-utils reads these via runtimeConfig.oauth.google.
    // Empty defaults — injected at runtime via NUXT_OAUTH_GOOGLE_* env vars.
    oauth: {
      google: {
        clientId: '',
        clientSecret: '',
      },
    },
    public: {
      // Browser-visible. Empty string = relative URLs, proxied through Nitro.
      apiBase: '',
    },
  },

  // ── App head ───────────────────────────────────────────────────────────
  app: {
    // Page transitions: soft out-in fade (classes in motion.css).
    // Automatically skipped for users with prefers-reduced-motion.
    pageTransition: { name: 'page', mode: 'out-in' },
    head: {
      htmlAttrs: { lang: 'en' },
      title: 'Lumi - A dictionary of the Taita language',
      meta: [
        { charset: 'utf-8' },
        { name: 'viewport', content: 'width=device-width, initial-scale=1' },
        {
          name: 'description',
          content:
            'Lumi is a community dictionary of the Taita language. Browse, search, and contribute Taita words with Swahili and English translations.',
        },
        // Open Graph + Twitter Card defaults. Per-page useSeoMeta() in each
        // page component overrides these with page-specific values.
        { property: 'og:title', content: 'Lumi — A dictionary of the Taita language' },
        { property: 'og:description', content: 'Browse, search, and contribute Taita words with Swahili and English translations.' },
        { property: 'og:type', content: 'website' },
        { property: 'og:image', content: '/og-default.png' },
        { name: 'twitter:card', content: 'summary_large_image' },
      ],
      link: [
        { rel: 'icon', type: 'image/svg+xml', href: '/favicon.svg' },
      ],
    },
  },

  // ── Route rules (hybrid rendering) ─────────────────────────────────────
  // Static-first since the dictionary snapshot landed (public/dictionary/ —
  // generated by scripts/export-dictionary.mjs before `nuxt build`):
  //
  //   prerender  — build-time static HTML served from the CDN edge with zero
  //                server function. Word pages read the local per-word JSON
  //                during prerender, so rendering never calls the backend.
  //   ssr        — always render fresh on the server (dynamic content).
  //   isr        — render once, cache at CDN, regenerate after expiry.
  //
  // Word pages: fully pre-rendered at build time. Words added after deploy
  // aren't in the snapshot — their /words/<slug> route isn't pre-rendered, so
  // Nitro renders it on demand (the page loads its data client-side from the
  // live API fallback) and the next deploy folds it into the snapshot.
  //
  // headers — CDN cache lifetimes. The snapshot and word HTML are immutable
  // per deploy (URLs carry a build id), so they can edge-cache for a day and
  // serve stale for a week while the next deploy revalidates. On Vercel,
  // routeRules (incl. headers) are compiled into the deployment config by
  // the nitro vercel preset — vercel.json stays minimal on purpose.
  routeRules: {
    // Pre-render at build time — the dictionary reads come from the snapshot
    '/words/**': {
      prerender: true,
      headers: { 'Cache-Control': 'public, max-age=0, s-maxage=86400, stale-while-revalidate=604800' },
    },
    '/':             { prerender: true },
    '/search':       { prerender: true }, // client-side search over the snapshot
    '/guide':        { prerender: true },
    '/support':      { prerender: true },
    '/contact':      { prerender: true },

    // SSR — dynamic content (suggestion queue + write actions)
    '/contribute':   { ssr: true },

    // Sitemap/robots — generated from the snapshot (server route reads
    // public/dictionary/sitemap-words.xml; no backend call). ISR so crawlers
    // share one render per hour.
    '/sitemap.xml':  { isr: 3600 },
    '/robots.txt':   { isr: 3600 },

    // ── Static dictionary snapshot ────────────────────────────────────────
    // The JSON the whole site reads — cache hard at the edge; browsers
    // revalidate each visit (max-age=0) so deploys propagate quickly.
    '/dictionary/words.json': {
      headers: { 'Cache-Control': 'public, max-age=0, s-maxage=86400, stale-while-revalidate=604800' },
    },
    '/dictionary/words/**': {
      headers: { 'Cache-Control': 'public, max-age=0, s-maxage=86400, stale-while-revalidate=604800' },
    },
    '/dictionary/manifest.json': {
      headers: { 'Cache-Control': 'public, max-age=0, s-maxage=3600' },
    },
  },

  // ── Nitro ──────────────────────────────────────────────────────────────
  // No devProxy — all /api/* requests are handled by Nitro server routes
  // (server/api/[...].ts catch-all + specific auth handlers). The proxy.ts
  // utility forwards to FastAPI directly via $fetch with auth + anon cookie.
  // ⚠️ Do NOT add nitro.devProxy — it intercepts /api/* before Nitro handlers
  // can run, bypassing auth and stripping the /api/ prefix.
  nitro: {
    // Vercel's CI auto-detects and sets its preset; the explicit fallback is
    // for local production builds/tests (node-server serves .output).
    preset: process.env.NITRO_PRESET || 'node-server',

    prerender: {
      // Crawl <NuxtLink> from pre-rendered pages to discover more routes
      // (home page links to recent words → those get pre-rendered too —
      // also covered by the manifest-driven hook below for every word).
      crawlLinks: true,

      // Don't fail the build if some routes can't be pre-rendered.
      failOnError: false,

      // Initial routes to pre-render. The word-page slugs are added
      // dynamically by the prerender:routes hook below, reading the static
      // snapshot manifest (public/dictionary/manifest.json).
      routes: ['/', '/search', '/guide', '/support', '/contact'],
    },
  },

  // ── Pre-render every word page from the static snapshot ────────────────
  // NOTE: this MUST be a Nuxt-level hook (not server/plugins/*, which are
  // runtime-only and never execute during `nuxt build` — the old
  // prerender-words.ts plugin silently never ran, hidden by its own
  // /api/words?size=10000 request 422ing against the backend's size≤100 cap).
  hooks: {
    'prerender:routes': async ({ routes }) => {
      const { readFile } = await import('node:fs/promises')
      let raw: string | null = null
      try {
        raw = await readFile('public/dictionary/manifest.json', 'utf8')
      } catch {
        raw = null
      }
      if (raw === null) {
        console.warn(
          '[prerender] public/dictionary/manifest.json missing — run `node scripts/export-dictionary.mjs` ' +
          'before the build. Word pages will render live at request time.',
        )
        return
      }
      const manifest = JSON.parse(raw) as { slugs?: string[]; total?: number }
      const slugs = Array.isArray(manifest.slugs) ? manifest.slugs : []
      let added = 0
      for (const slug of slugs) {
        if (slug) {
          routes.add(`/words/${slug}`)
          added++
        }
      }
      console.log(
        `[prerender] Added ${added} word routes from the static snapshot ` +
        `(manifest total: ${manifest.total ?? 'unknown'}).`,
      )
    },
  },
})
